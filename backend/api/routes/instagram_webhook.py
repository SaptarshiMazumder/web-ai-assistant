def _menu_view_all_url_for_category(category: str, items: List[Any]) -> str:
    preferred_tokens = {
        "course": ("/party",),
        "dish": ("/dtlmenu",),
        "drink": ("/dtlmenu/drink",),
        "lunch": ("/dtlmenu/lunch",),
    }
    urls: List[str] = []
    seen: set[str] = set()
    for item in items:
        u = _menu_item_source_url(item)
        if not u:
            continue
        key = u.lower()
        if key in seen:
            continue
        seen.add(key)
        urls.append(u)
    if not urls:
        return ""
    for u in urls:
        low = u.lower()
        for token in preferred_tokens.get(category, ()):
            if token in low:
                return u
    return urls[0]


def _merge_quick_replies(
    base: Optional[List[dict]],
    extra: Optional[List[dict]],
) -> Optional[List[dict]]:
    out: List[dict] = []
    seen: set[str] = set()
    for source in (extra or [], base or []):
        if not isinstance(source, dict):
            continue
        title = str(source.get("title") or "").strip()
        payload = str(source.get("payload") or "").strip()
        if not title or not payload:
            continue
        key = payload.lower()
        if key in seen:
            continue
        seen.add(key)
        out.append(
            {
                "content_type": "text",
                "title": title[:20],
                "payload": payload[:1000],
            }
        )
        if len(out) >= 13:
            break
    return out or None


