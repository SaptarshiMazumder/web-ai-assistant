async def _send_menu_by_category(
    *,
    bot_id: str,
    ig_user_id: str,
    access_token: str,
    quick_replies: Optional[List[dict]],
    page_category: Optional[str] = None,
    page_offset: int = 0,
    lang: str = "en",
    publishable_key: Optional[str] = None,
    request: Optional[Request] = None,
) -> None:
    items = _get_menu_items_for_bot(bot_id)
    if not items:
        _record_outbound_send(ig_user_id, bot_id)
        await send_message(
            ig_user_id,
            _menu_text("menu_not_ready", lang),
            access_token,
            quick_replies=quick_replies,
        )
        return

    menu_page_url = _menu_page_url(publishable_key, request) if publishable_key else None
    is_initial_menu = page_category is None and page_offset == 0

    if not menu_page_url and is_initial_menu and publishable_key:
        logger.info(
            "Instagram menu: menu_page_url empty (PUBLIC_BASE_URL or request host?). bot_id=%s pk=%s",
            bot_id,
            publishable_key,
        )

    if menu_page_url and is_initial_menu:
        prompt = _menu_text("view_menu_button_prompt", lang)
        btn_title = _menu_text("view_menu_button_title", lang)
        _record_outbound_send(ig_user_id, bot_id)
        sent = await send_button_template(
            recipient_id=ig_user_id,
            text=prompt,
            buttons=[{"type": "web_url", "url": menu_page_url, "title": btn_title[:20]}],
            page_access_token=access_token,
            quick_replies=quick_replies,
        )
        if sent:
            return
        logger.warning("Instagram menu button failed, falling back to text list")

    order = get_menu_category_order()
    grouped: Dict[str, List[Any]] = {k: [] for k in order}
    for item in items:
        grouped[_menu_category_for_item(item)].append(item)

    sent_any = False
    if page_category:
        categories = [page_category] if page_category in order else []
    else:
        categories = list(order)

    pending_more_qr: List[dict] = []
    for category in categories:
        category_items = grouped.get(category) or []
        if not category_items:
            continue
        label = _menu_category_label(category, lang)

        start = page_offset if page_category else 0
        page_items = category_items[start:start + _MENU_PAGE_SIZE]
        if not page_items:
            continue
        next_payload = None
        next_offset = start + _MENU_PAGE_SIZE
        if next_offset < len(category_items):
            next_payload = _make_menu_page_payload(category, next_offset)
        page_sent = await _send_menu_page_content(
            ig_user_id=ig_user_id,
            bot_id=bot_id,
            access_token=access_token,
            category=category,
            label=label,
            items=page_items,
            start=start,
            lang=lang,
            menu_page_url=menu_page_url,
        )
        sent_any = sent_any or page_sent
        if next_payload:
            pending_more_qr.append(
                {
                    "content_type": "text",
                    "title": _view_more_title(category, lang),
                    "payload": next_payload,
                }
            )
        if page_category:
            if next_payload:
                merged_qr = _merge_quick_replies(quick_replies, pending_more_qr)
                if merged_qr:
                    _record_outbound_send(ig_user_id, bot_id)
                    await send_message(
                        ig_user_id,
                        _menu_text("tap_view_more", lang),
                        access_token,
                        quick_replies=merged_qr,
                    )
            elif quick_replies:
                _record_outbound_send(ig_user_id, bot_id)
                await send_message(
                    ig_user_id,
                    _menu_text("choose_another", lang),
                    access_token,
                    quick_replies=quick_replies,
                )
            break

    if not sent_any:
        _record_outbound_send(ig_user_id, bot_id)
        await send_message(
            ig_user_id,
            _menu_text("render_error", lang),
            access_token,
            quick_replies=quick_replies,
        )
        return

    merged_qr = _merge_quick_replies(quick_replies, pending_more_qr)
    if merged_qr:
        prompt = _menu_text("more_items_prompt", lang) if pending_more_qr else _menu_text("choose_another", lang)
        await send_message(
            ig_user_id,
            prompt,
            access_token,
            quick_replies=merged_qr,
        )

    return


